import React, { useState } from 'react';
import { createPortal } from 'react-dom';
import { Printer, X, AlertTriangle, Clock, Search, Calendar, CheckCircle2 } from 'lucide-react';
import novaLogo from '../assets/nova-freshmart-logo.png';

export type ExpiryAlertItem = {
  id: string;
  productId: number;
  name: string;
  code: string;
  type: 'Product' | 'Variant' | 'Batch';
  detail: string;
  stock: number;
  unit: string;
  expiryDate: string;
  daysLeft: number;
};

interface ExpiryPrintModalProps {
  isOpen: boolean;
  onClose: () => void;
  alerts: ExpiryAlertItem[];
  currentUser: any;
  branchName?: string;
}

export default function ExpiryPrintModal({
  isOpen,
  onClose,
  alerts,
  currentUser,
  branchName = 'Main FreshMart Branch'
}: ExpiryPrintModalProps) {
  const [filter, setFilter] = useState<'all' | 'expired' | '1' | '7' | '30' | '90'>('all');
  const [search, setSearch] = useState('');

  if (!isOpen) return null;

  const expiredItems = alerts.filter(a => a.daysLeft <= 0);
  const today1Items = alerts.filter(a => a.daysLeft > 0 && a.daysLeft <= 1);
  const week7Items = alerts.filter(a => a.daysLeft > 0 && a.daysLeft <= 7);
  const urgent30Items = alerts.filter(a => a.daysLeft > 0 && a.daysLeft <= 30);
  const warning90Items = alerts.filter(a => a.daysLeft > 30 && a.daysLeft <= 90);

  const filteredAlerts = alerts.filter(a => {
    if (filter === 'expired' && a.daysLeft > 0) return false;
    if (filter === '1' && (a.daysLeft <= 0 || a.daysLeft > 1)) return false;
    if (filter === '7' && (a.daysLeft <= 0 || a.daysLeft > 7)) return false;
    if (filter === '30' && (a.daysLeft <= 0 || a.daysLeft > 30)) return false;
    if (filter === '90' && (a.daysLeft <= 30 || a.daysLeft > 90)) return false;

    if (search.trim()) {
      const q = search.toLowerCase();
      const matchName = a.name.toLowerCase().includes(q);
      const matchCode = (a.code || '').toLowerCase().includes(q);
      const matchDetail = (a.detail || '').toLowerCase().includes(q);
      return matchName || matchCode || matchDetail;
    }
    return true;
  });

  const totalStockAtRisk = alerts.reduce((acc, item) => acc + (Number(item.stock) || 0), 0);

  const handlePrint = () => {
    window.print();
  };

  const getStatusBadge = (days: number) => {
    if (days <= 0) {
      return (
        <span className="px-2.5 py-1 rounded-full text-xs font-black bg-red-100 text-red-700 border border-red-200">
          Expired {Math.abs(days)}d ago
        </span>
      );
    }
    if (days <= 30) {
      return (
        <span className="px-2.5 py-1 rounded-full text-xs font-black bg-orange-100 text-orange-800 border border-orange-200">
          {days} days left
        </span>
      );
    }
    return (
      <span className="px-2.5 py-1 rounded-full text-xs font-bold bg-amber-100 text-amber-800 border border-amber-200">
        {days} days left
      </span>
    );
  };

  const currentDateStr = new Date().toLocaleDateString('en-GB', {
    day: '2-digit',
    month: 'short',
    year: 'numeric'
  });
  const currentTimeStr = new Date().toLocaleTimeString('en-US', {
    hour: '2-digit',
    minute: '2-digit'
  });

  return (
    <>
      {/* On-Screen Modal Dialog */}
      <div className="fixed inset-0 bg-black/60 backdrop-blur-sm z-50 flex items-center justify-center p-4">
        <div className="bg-white rounded-3xl max-w-4xl w-full max-h-[92vh] flex flex-col shadow-2xl border border-gray-100 overflow-hidden">
          
          {/* Header */}
          <div className="p-6 border-b border-gray-100 flex items-center justify-between bg-gradient-to-r from-emerald-900 via-teal-900 to-slate-900 text-white shrink-0">
            <div className="flex items-center gap-3">
              <div className="w-12 h-12 rounded-2xl bg-amber-500/20 border border-amber-400/30 flex items-center justify-center text-amber-300">
                <AlertTriangle size={24} />
              </div>
              <div>
                <h3 className="font-black text-xl text-amber-300 tracking-tight flex items-center gap-2">
                  Inventory Expiry Warning Audit
                  <span className="text-xs bg-amber-400/20 text-amber-200 px-2 py-0.5 rounded-full font-bold">
                    Prior 3-Month Window
                  </span>
                </h3>
                <p className="text-xs text-emerald-200 font-medium">
                  {branchName} • Generated by {currentUser?.username || 'Staff'} • {alerts.length} item(s) found
                </p>
              </div>
            </div>
            <button
              onClick={onClose}
              className="text-white/60 hover:text-white p-2 rounded-xl hover:bg-white/10 transition-colors"
            >
              <X size={20} />
            </button>
          </div>

          {/* Quick Metrics Strip */}
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 p-5 bg-slate-50 border-b border-gray-200 shrink-0">
            <div className="bg-white p-3.5 rounded-2xl border border-gray-200 shadow-xs">
              <p className="text-[10px] font-black uppercase text-gray-400 tracking-wider">Total At-Risk SKUs</p>
              <p className="text-2xl font-black text-slate-800">{alerts.length}</p>
              <p className="text-[11px] font-bold text-gray-500 mt-0.5">{totalStockAtRisk} units in stock</p>
            </div>
            <div className="bg-red-50 p-3.5 rounded-2xl border border-red-200 shadow-xs">
              <p className="text-[10px] font-black uppercase text-red-600 tracking-wider">Already Expired</p>
              <p className="text-2xl font-black text-red-700">{expiredItems.length}</p>
              <p className="text-[11px] font-bold text-red-600 mt-0.5">Immediate disposal</p>
            </div>
            <div className="bg-orange-50 p-3.5 rounded-2xl border border-orange-200 shadow-xs">
              <p className="text-[10px] font-black uppercase text-orange-700 tracking-wider">Urgent (&lt; 30 Days)</p>
              <p className="text-2xl font-black text-orange-800">{urgent30Items.length}</p>
              <p className="text-[11px] font-bold text-orange-700 mt-0.5">Discount or return</p>
            </div>
            <div className="bg-amber-50 p-3.5 rounded-2xl border border-amber-200 shadow-xs">
              <p className="text-[10px] font-black uppercase text-amber-700 tracking-wider">Within 3 Months (30-90d)</p>
              <p className="text-2xl font-black text-amber-800">{warning90Items.length}</p>
              <p className="text-[11px] font-bold text-amber-700 mt-0.5">FIFO rotation priority</p>
            </div>
          </div>

          {/* Search & Filter Toolbar */}
          <div className="p-4 border-b border-gray-100 flex flex-col sm:flex-row items-center justify-between gap-3 shrink-0">
            <div className="flex items-center gap-1.5 bg-gray-100 p-1 rounded-2xl border border-gray-200 w-full sm:w-auto">
              <button
                onClick={() => setFilter('all')}
                className={`px-3 py-1.5 rounded-xl text-xs font-black transition-all ${
                  filter === 'all' ? 'bg-white text-slate-900 shadow-xs' : 'text-gray-500 hover:text-gray-800'
                }`}
              >
                All (90d Alert) ({alerts.length})
              </button>
              <button
                onClick={() => setFilter('expired')}
                className={`px-3 py-1.5 rounded-xl text-xs font-black transition-all ${
                  filter === 'expired' ? 'bg-red-600 text-white shadow-xs' : 'text-gray-500 hover:text-red-700'
                }`}
              >
                Expired ({expiredItems.length})
              </button>
              <button
                onClick={() => setFilter('1')}
                className={`px-3 py-1.5 rounded-xl text-xs font-black transition-all ${
                  filter === '1' ? 'bg-rose-500 text-white shadow-xs' : 'text-gray-500 hover:text-rose-700'
                }`}
              >
                Today ({today1Items.length})
              </button>
              <button
                onClick={() => setFilter('7')}
                className={`px-3 py-1.5 rounded-xl text-xs font-black transition-all ${
                  filter === '7' ? 'bg-amber-600 text-white shadow-xs' : 'text-gray-500 hover:text-amber-700'
                }`}
              >
                1 Wk ({week7Items.length})
              </button>
              <button
                onClick={() => setFilter('30')}
                className={`px-3 py-1.5 rounded-xl text-xs font-black transition-all ${
                  filter === '30' ? 'bg-orange-500 text-white shadow-xs' : 'text-gray-500 hover:text-orange-700'
                }`}
              >
                &lt; 30 Days ({urgent30Items.length})
              </button>
              <button
                onClick={() => setFilter('90')}
                className={`px-3 py-1.5 rounded-xl text-xs font-black transition-all ${
                  filter === '90' ? 'bg-amber-500 text-white shadow-xs' : 'text-gray-500 hover:text-amber-800'
                }`}
              >
                30-90 Days ({warning90Items.length})
              </button>
            </div>

            <div className="relative w-full sm:w-64">
              <Search size={16} className="absolute left-3.5 top-1/2 -translate-y-1/2 text-gray-400" />
              <input
                type="text"
                placeholder="Search product, barcode..."
                value={search}
                onChange={e => setSearch(e.target.value)}
                className="w-full pl-9 pr-4 py-2 border border-gray-200 rounded-xl text-xs font-bold outline-none focus:border-brand-primary"
              />
            </div>
          </div>

          {/* Table List View */}
          <div className="flex-1 overflow-y-auto">
            {filteredAlerts.length === 0 ? (
              <div className="flex flex-col items-center justify-center p-12 text-center text-gray-400">
                <CheckCircle2 size={48} className="text-emerald-500 mb-2 opacity-80" />
                <p className="font-black text-slate-700 text-base">No Products Found In Selected Filter</p>
                <p className="text-xs text-gray-400 mt-1">
                  {search ? 'Try adjusting your search keywords.' : 'All items in this range are within safe dates.'}
                </p>
              </div>
            ) : (
              <table className="w-full text-left border-collapse">
                <thead className="bg-gray-50 text-[10px] font-black uppercase text-gray-400 tracking-wider sticky top-0 border-b border-gray-200 z-10">
                  <tr>
                    <th className="py-3 px-4">#</th>
                    <th className="py-3 px-4">Product Name</th>
                    <th className="py-3 px-4">Barcode / PLU</th>
                    <th className="py-3 px-4">Inventory Type</th>
                    <th className="py-3 px-4 text-right">Available Stock</th>
                    <th className="py-3 px-4 text-center">Expiry Date</th>
                    <th className="py-3 px-4 text-center">Remaining</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-gray-100 text-xs">
                  {filteredAlerts.map((item, idx) => (
                    <tr key={item.id} className="hover:bg-slate-50/80 transition-colors">
                      <td className="py-3 px-4 text-gray-400 font-bold">{idx + 1}</td>
                      <td className="py-3 px-4 font-black text-slate-800">{item.name}</td>
                      <td className="py-3 px-4 font-mono font-bold text-gray-600">{item.code || '-'}</td>
                      <td className="py-3 px-4">
                        <span className={`px-2 py-0.5 rounded text-[10px] font-bold ${
                          item.type === 'Variant' 
                            ? 'bg-purple-100 text-purple-700' 
                            : item.type === 'Batch' 
                            ? 'bg-blue-100 text-blue-700' 
                            : 'bg-emerald-100 text-emerald-800'
                        }`}>
                          {item.type}
                        </span>
                        <span className="text-[11px] text-gray-500 ml-1.5">{item.detail}</span>
                      </td>
                      <td className="py-3 px-4 text-right font-black text-slate-900">
                        {item.stock} <span className="text-gray-400 text-[10px]">{item.unit}</span>
                      </td>
                      <td className="py-3 px-4 text-center font-bold text-slate-700">
                        {item.expiryDate}
                      </td>
                      <td className="py-3 px-4 text-center">
                        {getStatusBadge(item.daysLeft)}
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            )}
          </div>

          {/* Footer Actions */}
          <div className="p-4 border-t border-gray-100 bg-gray-50 flex items-center justify-between shrink-0">
            <div className="text-xs text-gray-500 font-medium">
              Showing <span className="font-black text-slate-800">{filteredAlerts.length}</span> of {alerts.length} item(s)
            </div>
            <div className="flex items-center gap-3">
              <button
                type="button"
                onClick={onClose}
                className="px-5 py-2.5 rounded-xl border border-gray-300 font-bold text-gray-600 hover:bg-gray-100 text-xs transition-colors"
              >
                Close
              </button>
              <button
                type="button"
                onClick={handlePrint}
                className="px-6 py-2.5 rounded-xl bg-brand-primary hover:bg-brand-secondary text-white font-black text-xs flex items-center gap-2 shadow-md shadow-brand-primary/20 transition-all cursor-pointer"
              >
                <Printer size={16} />
                <span>Print Expiry Audit Report</span>
              </button>
            </div>
          </div>

        </div>
      </div>

      {/* High-Resolution Printable Report Rendered Directly Into Document Body */}
      {createPortal(
        <div className="print-report-only">
          <div style={{ fontFamily: 'Arial, sans-serif', color: '#000', padding: '10px' }}>
            {/* Store Letterhead */}
            <div style={{ borderBottom: '2px solid #000', paddingBottom: '10px', marginBottom: '14px', display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start' }}>
              <div>
                <h1 style={{ margin: 0, fontSize: '20px', fontWeight: 'bold', textTransform: 'uppercase', letterSpacing: '1px' }}>
                  Nova FreshMart Supermarket
                </h1>
                <p style={{ margin: '3px 0 0', fontSize: '13px', fontWeight: 'bold' }}>
                  INVENTORY EXPIRY ALERT AUDIT REPORT
                </p>
                <p style={{ margin: '2px 0 0', fontSize: '11px', color: '#444' }}>
                  Prior 3 Months (90-Day Warning) &amp; Expired Inventory Audit
                </p>
                <p style={{ margin: '2px 0 0', fontSize: '10px', color: '#555' }}>
                  Branch: {branchName} • Generated By: {currentUser?.username || 'Staff Auditor'}
                </p>
              </div>
              <div style={{ textAlign: 'right' }}>
                <p style={{ margin: 0, fontSize: '11px', fontWeight: 'bold' }}>Date: {currentDateStr}</p>
                <p style={{ margin: '2px 0 0', fontSize: '10px' }}>Time: {currentTimeStr}</p>
                <p style={{ margin: '4px 0 0', fontSize: '11px', fontWeight: 'bold', color: '#b91c1c' }}>
                  Total Items: {alerts.length} SKUs
                </p>
                <p style={{ margin: '2px 0 0', fontSize: '10px', fontWeight: 'bold' }}>
                  Total Units at Risk: {totalStockAtRisk}
                </p>
              </div>
            </div>

            {/* Audit Summary Box */}
            <div style={{ display: 'grid', gridTemplateColumns: 'repeat(4, 1fr)', gap: '8px', marginBottom: '14px', border: '1px solid #ccc', padding: '8px', borderRadius: '4px', background: '#fafafa' }}>
              <div style={{ textAlign: 'center' }}>
                <div style={{ fontSize: '9px', fontWeight: 'bold', textTransform: 'uppercase', color: '#666' }}>Total SKUs</div>
                <div style={{ fontSize: '14px', fontWeight: 'bold' }}>{alerts.length}</div>
              </div>
              <div style={{ textAlign: 'center' }}>
                <div style={{ fontSize: '9px', fontWeight: 'bold', textTransform: 'uppercase', color: '#b91c1c' }}>Expired</div>
                <div style={{ fontSize: '14px', fontWeight: 'bold', color: '#b91c1c' }}>{expiredItems.length}</div>
              </div>
              <div style={{ textAlign: 'center' }}>
                <div style={{ fontSize: '9px', fontWeight: 'bold', textTransform: 'uppercase', color: '#c2410c' }}>&lt; 30 Days</div>
                <div style={{ fontSize: '14px', fontWeight: 'bold', color: '#c2410c' }}>{urgent30Items.length}</div>
              </div>
              <div style={{ textAlign: 'center' }}>
                <div style={{ fontSize: '9px', fontWeight: 'bold', textTransform: 'uppercase', color: '#b45309' }}>30 - 90 Days</div>
                <div style={{ fontSize: '14px', fontWeight: 'bold', color: '#b45309' }}>{warning90Items.length}</div>
              </div>
            </div>

            {/* Audit Table */}
            <table style={{ width: '100%', borderCollapse: 'collapse', fontSize: '10px' }}>
              <thead>
                <tr style={{ background: '#eee', borderTop: '1.5px solid #000', borderBottom: '1.5px solid #000' }}>
                  <th style={{ padding: '6px 4px', textAlign: 'left', width: '28px' }}>#</th>
                  <th style={{ padding: '6px 6px', textAlign: 'left' }}>Product Name</th>
                  <th style={{ padding: '6px 6px', textAlign: 'left', width: '100px' }}>Barcode / PLU</th>
                  <th style={{ padding: '6px 6px', textAlign: 'left', width: '110px' }}>Type / Batch</th>
                  <th style={{ padding: '6px 6px', textAlign: 'right', width: '80px' }}>Available Qty</th>
                  <th style={{ padding: '6px 6px', textAlign: 'center', width: '85px' }}>Expiry Date</th>
                  <th style={{ padding: '6px 6px', textAlign: 'center', width: '95px' }}>Status</th>
                </tr>
              </thead>
              <tbody>
                {alerts.map((item, idx) => (
                  <tr key={item.id} style={{ borderBottom: '1px solid #ddd' }}>
                    <td style={{ padding: '5px 4px', textAlign: 'left', color: '#666' }}>{idx + 1}</td>
                    <td style={{ padding: '5px 6px', textAlign: 'left', fontWeight: 'bold' }}>{item.name}</td>
                    <td style={{ padding: '5px 6px', textAlign: 'left', fontFamily: 'monospace' }}>{item.code || '-'}</td>
                    <td style={{ padding: '5px 6px', textAlign: 'left' }}>
                      {item.type === 'Product' ? 'Main Stock' : item.detail}
                    </td>
                    <td style={{ padding: '5px 6px', textAlign: 'right', fontWeight: 'bold' }}>
                      {item.stock} {item.unit}
                    </td>
                    <td style={{ padding: '5px 6px', textAlign: 'center', fontWeight: 'bold' }}>
                      {item.expiryDate}
                    </td>
                    <td style={{ padding: '5px 6px', textAlign: 'center', fontWeight: 'bold', color: item.daysLeft <= 0 ? '#b91c1c' : item.daysLeft <= 30 ? '#c2410c' : '#b45309' }}>
                      {item.daysLeft <= 0 ? `EXPIRED (${Math.abs(item.daysLeft)}d ago)` : `${item.daysLeft}d left`}
                    </td>
                  </tr>
                ))}
                {alerts.length === 0 && (
                  <tr>
                    <td colSpan={7} style={{ padding: '20px', textAlign: 'center', color: '#666', fontStyle: 'italic' }}>
                      No inventory items found expiring within the selected 3-month window.
                    </td>
                  </tr>
                )}
              </tbody>
            </table>

            {/* Audit Sign-Off Section */}
            <div style={{ marginTop: '24px', paddingTop: '12px', borderTop: '1.5px solid #000', display: 'flex', justifyContent: 'space-between', fontSize: '10px' }}>
              <div>
                <p style={{ margin: 0, fontWeight: 'bold' }}>Audited &amp; Checked By:</p>
                <p style={{ margin: '14px 0 0', borderBottom: '1px solid #000', width: '180px' }}></p>
                <p style={{ margin: '4px 0 0', color: '#666' }}>Name: {currentUser?.username || 'Staff'}</p>
              </div>
              <div>
                <p style={{ margin: 0, fontWeight: 'bold' }}>Branch Manager Authorization:</p>
                <p style={{ margin: '14px 0 0', borderBottom: '1px solid #000', width: '180px' }}></p>
                <p style={{ margin: '4px 0 0', color: '#666' }}>Signature &amp; Stamp</p>
              </div>
              <div style={{ width: '220px' }}>
                <p style={{ margin: 0, fontWeight: 'bold' }}>Action Decision Taken:</p>
                <p style={{ margin: '4px 0 0' }}>[  ] Clear at Promotional Discount</p>
                <p style={{ margin: '2px 0 0' }}>[  ] Return to Supplier for Credit</p>
                <p style={{ margin: '2px 0 0' }}>[  ] Quarantine / Dispose from Stock</p>
              </div>
            </div>
          </div>
        </div>,
        document.body
      )}
    </>
  );
}
